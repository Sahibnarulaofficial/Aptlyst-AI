"""Durable background worker for Razorpay webhook event processing.

Architecture & Invariants:
1. Persisted Leased Processing:
   - Claims events via SELECT ... FOR UPDATE SKIP LOCKED and stamps an explicit database lease.
   - Commits the claim immediately, releasing the database row lock before running the handler.
   - No database transaction or row lock is held during external network calls or handler execution.
2. Fencing Token Verification:
   - Re-acquires row lock during outcome recording to verify lease ownership and expiry.
   - Stale workers (whose lease expired or was superseded) are rejected with StaleLeaseError.
3. Safe Retry & Quarantine:
   - Respects 5-attempt quarantine threshold.
   - Applies 5s / 15s / 45s / 120s exponential backoff schedule.
   - Lease expiry recovery does not increment attempts.
4. Graceful Shutdown:
   - Listens for SIGINT/SIGTERM, allowing any in-flight event to complete cleanly before exit.
5. Zero Secret Leakage:
   - Error summaries are sanitized before recording or logging.
"""

import argparse
import asyncio
from collections.abc import Callable
from datetime import datetime, timezone
import inspect
import logging
import os
import signal
import sys
from typing import Any
import uuid

# Ensure apps/api directory is in sys.path when executed directly as a script
_CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))
_API_ROOT = os.path.abspath(os.path.join(_CURRENT_DIR, "..", ".."))
if _API_ROOT not in sys.path:
    sys.path.insert(0, _API_ROOT)

from sqlalchemy.ext.asyncio import AsyncSession

from app.db.session import AsyncSessionLocal
from app.models.subscription import WebhookProcessingStatus
from app.services.billing.razorpay.webhook_engine import (
    DEFAULT_LEASE_DURATION_SECONDS,
    MAX_WEBHOOK_ATTEMPTS,
    ClaimedWebhookEvent,
    ProcessingOutcome,
    ProcessResult,
    RazorpayWebhookDispatcher,
    RazorpayWebhookPermanentError,
    RazorpayWebhookRetryableError,
    StaleLeaseError,
    claim_next_razorpay_webhook_event,
    default_razorpay_dispatcher,
    record_razorpay_webhook_outcome,
)

logger = logging.getLogger("app.workers.razorpay_webhook_worker")

DEFAULT_POLL_INTERVAL_SECONDS: float = 2.0
DEFAULT_BATCH_SIZE: int = 10


class RazorpayWebhookWorker:
    """Dedicated background worker that continuously claims and processes Razorpay webhook events."""

    def __init__(
        self,
        session_factory: Callable[[], AsyncSession] | None = None,
        dispatcher: RazorpayWebhookDispatcher | None = None,
        worker_id: str | None = None,
        lease_duration: int | None = None,
        poll_interval: float | None = None,
        batch_size: int | None = None,
        max_attempts: int | None = None,
        environment: str | None = None,
        clock: Callable[[], datetime] | None = None,
    ) -> None:
        """Initialize the Razorpay webhook worker.

        Args:
            session_factory: Callable returning an AsyncSession (defaults to AsyncSessionLocal).
            dispatcher: RazorpayWebhookDispatcher instance (defaults to default_razorpay_dispatcher).
            worker_id: Unique worker identifier (defaults to autogenerated UUID-based ID).
            lease_duration: Seconds a claimed lease remains valid (defaults to 60s).
            poll_interval: Seconds to wait between polling loops when queue is empty.
            batch_size: Maximum number of events to claim per batch iteration.
            max_attempts: Maximum retry threshold before quarantine.
            environment: Optional environment filter ("test" or "live").
            clock: Optional callable returning current UTC datetime (for testing).
        """
        self.session_factory = session_factory or AsyncSessionLocal
        self.dispatcher = dispatcher or default_razorpay_dispatcher
        self.worker_id = worker_id or f"worker_rzp_{uuid.uuid4().hex[:12]}"
        self.lease_duration = (
            lease_duration if lease_duration is not None else DEFAULT_LEASE_DURATION_SECONDS
        )

        env_poll = os.getenv("RAZORPAY_WEBHOOK_WORKER_POLL_INTERVAL")
        env_batch = os.getenv("RAZORPAY_WEBHOOK_WORKER_BATCH_SIZE")

        self.poll_interval = (
            poll_interval
            if poll_interval is not None
            else (float(env_poll) if env_poll else DEFAULT_POLL_INTERVAL_SECONDS)
        )
        self.batch_size = (
            batch_size
            if batch_size is not None
            else (int(env_batch) if env_batch else DEFAULT_BATCH_SIZE)
        )
        self.max_attempts = (
            max_attempts if max_attempts is not None else MAX_WEBHOOK_ATTEMPTS
        )
        self.environment = environment
        self.clock = clock

        if self.poll_interval <= 0:
            raise ValueError(f"poll_interval must be greater than 0, got {self.poll_interval}")
        if self.batch_size < 1:
            raise ValueError(f"batch_size must be at least 1, got {self.batch_size}")
        if self.max_attempts < 1:
            raise ValueError(f"max_attempts must be at least 1, got {self.max_attempts}")

        self._stop_event = asyncio.Event()
        self._signal_handlers_registered = False

    def _get_now(self) -> datetime:
        """Get current UTC timestamp, using clock callable if configured."""
        if self.clock is not None:
            return self.clock()
        return datetime.now(timezone.utc)

    async def claim_one(self) -> ClaimedWebhookEvent | None:
        """Claim a single eligible event under a fresh lease.

        Returns:
            ClaimedWebhookEvent if successfully leased, or None if no eligible event exists.
        """
        now = self._get_now()
        async with self.session_factory() as db:
            try:
                claimed = await claim_next_razorpay_webhook_event(
                    db=db,
                    worker_id=self.worker_id,
                    lease_duration_seconds=self.lease_duration,
                    max_attempts=self.max_attempts,
                    environment=self.environment,
                    now=now,
                )
                return claimed
            except Exception as exc:
                logger.error("Error while worker %s claimed event: %s", self.worker_id, exc)
                return None

    async def process_one(self) -> ProcessResult | None:
        """Claim, execute, and record outcome for a single webhook event.

        Guarantees:
        - Network/handler calls execute outside the database claim transaction.
        - The outcome recording transaction validates fencing (lease_token and expiry).
        - If ownership was lost, StaleLeaseError is caught and no business mutations commit.

        Returns:
            ProcessResult if an event was claimed and executed, or None if queue is empty.
        """
        claimed = await self.claim_one()
        if claimed is None:
            return None

        # Execute handler outside of DB claim transaction
        handler = self.dispatcher.get_handler(claimed.event_type)
        if handler is None:
            outcome = ProcessingOutcome.UNKNOWN_EVENT
            err_to_record: Exception | str | None = f"No handler registered for event type '{claimed.event_type}'"
        else:
            try:
                async with self.session_factory() as handler_db:
                    sig = inspect.signature(handler)
                    params = list(sig.parameters.values())
                    if params and params[0].name in ("event", "claimed", "ctx", "context"):
                        await handler(claimed, handler_db)
                    else:
                        await handler(claimed.payload, handler_db)
                outcome = ProcessingOutcome.SUCCESS
                err_to_record = None
            except StaleLeaseError as exc:
                logger.warning(
                    "Worker %s aborted domain execution: lost lease on event %s: %s",
                    self.worker_id,
                    claimed.event_id,
                    exc,
                )
                return ProcessResult(
                    success=False,
                    status=WebhookProcessingStatus.failed,
                    event_id=claimed.event_id,
                    provider_event_id=claimed.provider_event_id,
                    attempts=claimed.attempts,
                    message=f"Fencing rejected stale worker during domain execution: {exc}",
                    error=exc,
                )
            except RazorpayWebhookPermanentError as exc:
                outcome = ProcessingOutcome.PERMANENT_FAILURE
                err_to_record = exc
            except (RazorpayWebhookRetryableError, Exception) as exc:
                outcome = ProcessingOutcome.RETRYABLE_FAILURE
                err_to_record = exc

        # Complete event in a short transaction with fencing validation
        now_outcome = self._get_now()
        async with self.session_factory() as outcome_db:
            try:
                updated_event = await record_razorpay_webhook_outcome(
                    db=outcome_db,
                    claimed=claimed,
                    outcome=outcome,
                    error=err_to_record,
                    max_attempts=self.max_attempts,
                    now=now_outcome,
                )
                logger.info(
                    "Worker %s completed event %s (outcome=%s, status=%s, attempts=%d)",
                    self.worker_id,
                    claimed.event_id,
                    outcome.value,
                    updated_event.status.value,
                    updated_event.attempts,
                )
                return ProcessResult(
                    success=(outcome == ProcessingOutcome.SUCCESS),
                    status=updated_event.status,
                    event_id=claimed.event_id,
                    provider_event_id=claimed.provider_event_id,
                    attempts=updated_event.attempts,
                    message=f"Outcome recorded: {outcome.value}",
                )
            except StaleLeaseError as exc:
                logger.warning(
                    "Worker %s lost ownership of event %s. Fencing rejected completion: %s",
                    self.worker_id,
                    claimed.event_id,
                    exc,
                )
                return ProcessResult(
                    success=False,
                    status=WebhookProcessingStatus.failed,
                    event_id=claimed.event_id,
                    provider_event_id=claimed.provider_event_id,
                    attempts=claimed.attempts,
                    message="Lease lost or expired; completion rejected",
                    error=exc,
                )
            except Exception as exc:
                logger.error(
                    "Unexpected error recording outcome for event %s: %s",
                    claimed.event_id,
                    exc,
                    exc_info=True,
                )
                return None

    async def run_batch(self, max_count: int | None = None) -> list[ProcessResult]:
        """Claim and process a batch of eligible events up to max_count or batch_size.

        Args:
            max_count: Optional override for batch limit.

        Returns:
            List of ProcessResult instances for claimed events.
        """
        limit = max_count if max_count is not None else self.batch_size
        results: list[ProcessResult] = []

        for _ in range(limit):
            if self._stop_event.is_set():
                break

            result = await self.process_one()
            if result is None:
                # No more events ready or all active rows locked
                break
            results.append(result)

        return results

    async def run_once(self) -> int:
        """Process currently available eligible events in a single pass and return count.

        Returns:
            Number of events processed.
        """
        results = await self.run_batch()
        return len(results)

    async def run_forever(self) -> None:
        """Continuously poll and process events until stop() is invoked."""
        await self.start()

    async def start(self) -> None:
        """Run the worker polling loop until stopped."""
        logger.info(
            "Starting RazorpayWebhookWorker %s (poll_interval=%.2fs, batch_size=%d, lease_duration=%ds, max_attempts=%d)",
            self.worker_id,
            self.poll_interval,
            self.batch_size,
            self.lease_duration,
            self.max_attempts,
        )
        while not self._stop_event.is_set():
            try:
                results = await self.run_batch()
                if results:
                    # If full batch was processed, immediately poll again without delay
                    if len(results) >= self.batch_size:
                        continue
                else:
                    # Queue is empty, back off for poll_interval
                    try:
                        await asyncio.wait_for(
                            self._stop_event.wait(), timeout=self.poll_interval
                        )
                    except asyncio.TimeoutError:
                        pass
            except asyncio.CancelledError:
                break
            except Exception as exc:
                logger.error("Error in RazorpayWebhookWorker polling loop: %s", exc, exc_info=True)
                try:
                    await asyncio.wait_for(
                        self._stop_event.wait(), timeout=min(5.0, self.poll_interval)
                    )
                except asyncio.TimeoutError:
                    pass

        logger.info("RazorpayWebhookWorker %s stopped cleanly.", self.worker_id)

    def stop(self) -> None:
        """Signal the worker polling loop to stop gracefully."""
        logger.info("Stopping RazorpayWebhookWorker %s...", self.worker_id)
        self._stop_event.set()


def setup_signal_handlers(worker: RazorpayWebhookWorker) -> None:
    """Register signal handlers for graceful shutdown across POSIX and Windows environments.

    Guarantees:
    - Avoids duplicate signal-handler registration on the worker.
    - Gracefully stops accepting new work upon SIGINT/SIGTERM while allowing in-flight events to finish.
    - Handles POSIX event loop signal handlers and Windows sync signal handlers.
    """
    if getattr(worker, "_signal_handlers_registered", False):
        logger.debug("Signal handlers already registered for worker %s.", worker.worker_id)
        return

    def _on_signal() -> None:
        logger.info(
            "Termination signal received for worker %s. Requesting graceful shutdown...",
            worker.worker_id,
        )
        worker.stop()

    try:
        loop = asyncio.get_running_loop()
        for sig in (signal.SIGINT, signal.SIGTERM):
            loop.add_signal_handler(sig, _on_signal)
        worker._signal_handlers_registered = True
        logger.debug("Registered asyncio loop signal handlers for worker %s.", worker.worker_id)
    except (NotImplementedError, AttributeError, RuntimeError):
        # Fallback for Windows or environments where add_signal_handler is unsupported
        try:
            def _sync_signal_handler(signum: int, frame: Any) -> None:
                _on_signal()

            signal.signal(signal.SIGINT, _sync_signal_handler)
            signal.signal(signal.SIGTERM, _sync_signal_handler)
            worker._signal_handlers_registered = True
            logger.debug("Registered sync signal handlers for worker %s.", worker.worker_id)
        except (ValueError, AttributeError) as exc:
            logger.warning(
                "Could not register signal handlers for worker %s (e.g. running in thread): %s",
                worker.worker_id,
                exc,
            )


async def run_worker(
    poll_interval: float | None = None,
    batch_size: int | None = None,
    max_attempts: int | None = None,
    run_once_only: bool = False,
    session_factory: Callable[[], AsyncSession] | None = None,
    dispatcher: RazorpayWebhookDispatcher | None = None,
    environment: str | None = None,
) -> int:
    """Run the Razorpay webhook worker as an async task with signal interception.

    Args:
        poll_interval: Seconds between polls when queue is idle.
        batch_size: Maximum events claimed and executed per batch iteration.
        max_attempts: Maximum retry attempts before quarantining an unprocessable event.
        run_once_only: If True, executes a single batch pass and returns.
        session_factory: Optional custom AsyncSession factory (used for testing).
        dispatcher: Optional custom dispatcher instance.
        environment: Optional environment filter ("test" or "live").

    Returns:
        Exit code (0 on clean shutdown).
    """
    if poll_interval is not None and poll_interval <= 0:
        raise ValueError(f"poll_interval must be greater than 0, got {poll_interval}")
    if batch_size is not None and batch_size < 1:
        raise ValueError(f"batch_size must be at least 1, got {batch_size}")
    if max_attempts is not None and max_attempts < 1:
        raise ValueError(f"max_attempts must be at least 1, got {max_attempts}")

    worker = RazorpayWebhookWorker(
        session_factory=session_factory,
        dispatcher=dispatcher,
        poll_interval=poll_interval,
        batch_size=batch_size,
        max_attempts=max_attempts,
        environment=environment,
    )

    setup_signal_handlers(worker)

    try:
        if run_once_only:
            count = await worker.run_once()
            logger.info("Single batch pass completed: %d events processed.", count)
            return 0

        await worker.start()
        return 0
    finally:
        if session_factory is None:
            try:
                from app.db.session import engine

                await engine.dispose()
                logger.debug("Disposed default database engine successfully.")
            except Exception as exc:
                logger.debug("Error disposing database engine: %s", exc)


def build_parser() -> argparse.ArgumentParser:
    """Construct CLI argument parser for the Razorpay webhook worker."""
    parser = argparse.ArgumentParser(
        prog="python -m app.workers.razorpay_webhook_worker",
        description="Aptlyst AI — Durable Razorpay Webhook Processing Worker",
    )
    parser.add_argument(
        "--poll-interval",
        type=float,
        default=None,
        help=f"Seconds to wait between polling loops when queue is idle (default: {DEFAULT_POLL_INTERVAL_SECONDS})",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=None,
        help=f"Maximum events to claim and execute per batch iteration (default: {DEFAULT_BATCH_SIZE})",
    )
    parser.add_argument(
        "--max-attempts",
        type=int,
        default=None,
        help=f"Maximum attempts before quarantining an unprocessable event (default: {MAX_WEBHOOK_ATTEMPTS})",
    )
    parser.add_argument(
        "--once",
        action="store_true",
        help="Execute a single pass over pending events and exit immediately",
    )
    parser.add_argument(
        "--log-level",
        type=str,
        default="INFO",
        choices=["DEBUG", "INFO", "WARNING", "ERROR"],
        help="Logging verbosity level (default: INFO)",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    """CLI entrypoint for running the Razorpay webhook worker."""
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.poll_interval is not None and args.poll_interval <= 0:
        parser.error("--poll-interval must be greater than 0")
    if args.batch_size is not None and args.batch_size < 1:
        parser.error("--batch-size must be at least 1")
    if args.max_attempts is not None and args.max_attempts < 1:
        parser.error("--max-attempts must be at least 1")

    logging.basicConfig(
        level=getattr(logging, args.log_level.upper(), logging.INFO),
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    )

    try:
        exit_code = asyncio.run(
            run_worker(
                poll_interval=args.poll_interval,
                batch_size=args.batch_size,
                max_attempts=args.max_attempts,
                run_once_only=args.once,
            )
        )
        sys.exit(exit_code)
    except KeyboardInterrupt:
        logger.info("Received KeyboardInterrupt. Exiting...")
        sys.exit(0)


if __name__ == "__main__":
    main()
